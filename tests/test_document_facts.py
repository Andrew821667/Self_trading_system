"""Ловушки разбора цены и даты в процедурных сообщениях.

Каждый случай здесь — не гипотеза, а строка из конкретного документа, на
которой один из трёх прежних параллельных парсеров молча выдавал неверное
число. Молча — ключевое слово: ошибка не роняла разбор, она подставляла
правдоподобную цену, и заметить её можно было только сверкой с текстом.
Поэтому тесты держат именно эти формулировки, а не упрощённые образцы.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))

from document_facts import parse_date, parse_price


@pytest.mark.parametrize(
    ("text", "expected"),
    [
        # Рубли целые + копейки отдельно — их надо сложить.
        ("481 (Четыреста восемьдесят один) рубль 68 копеек", "481.68"),
        # То же, но копейки продублированы прописью.
        ("234 (двести тридцать четыре) рубля 75 (семьдесят пять) копеек", "234.75"),
        # Рубли уже дробные, а скобка повторяет ту же цену другими словами.
        # Сложение давало 1,50 — ровно вдвое больше действительной цены выкупа.
        ("0,75 рубля (75 копеек) за 1 (одну) акцию", "0.75"),
        ("80,81 рублей (Восемьдесят рублей 81 копейка) за одну акцию", "80.81"),
        # Цена ниже рубля: слова "рубль" рядом с числом нет вовсе.
        ("61 (шестьдесят одна) копейка за 1 (одну) акцию", "0.61"),
        # Слово "рубль" есть только внутри расшифровки прописью.
        ("1,89 (один рубль восемьдесят девять копеек) за одну акцию", "1.89"),
        # Доли копейки — законная цена, а не сбой распознавания.
        ("Цена приобретения одной обыкновенной акции составляет 0,00289 рублей", "0.00289"),
        # Вытеснение по ст. 84.8 после санации: цена записана дробью.
        (
            "1 / 4 507 984 112 (Одна четырехмиллиардная ... доля) рубля за 1 (одну) акцию",
            "0.0000000002",
        ),
    ],
)
def test_parse_price(text: str, expected: str) -> None:
    assert parse_price(text) == expected


@pytest.mark.parametrize(
    ("text", "expected"),
    [
        ("о котором составлено сообщение: 30.07.2025", "2025-07-30"),
        # Прописью — в шапке и в пункте 2.4 одного и того же документа.
        ("Дата получения эмитентом требования: 14 декабря 2020 года", "2020-12-14"),
        ("о котором составлено сообщение 02 июня 2020 г.", "2020-06-02"),
        ("31 марта 2025 года", "2025-03-31"),
        ("1 мая 2021 г.", "2021-05-01"),
    ],
)
def test_parse_date(text: str, expected: str) -> None:
    assert parse_date(text) == expected


@pytest.mark.parametrize(
    ("text", "expected"),
    [
        # "0,592 (ноль целых пятьсот девяносто две тысячных) рубля" читалось
        # как 592: дробная часть была ограничена двумя знаками, "0,59" под
        # "рубля" не подходило, зато подходило "592" из середины числа.
        # Ошибка в тысячу раз, у ПАО "ТНС энерго Ростов-на-Дону".
        ("Цена – 0,592 (ноль целых пятьсот девяносто две тысячных) рубля за одну акцию", "0.592"),
        # "1,12 рублей (Один рубль 12 копеек)" складывалось в 1,24.
        ("1,12 рублей (Один рубль 12 копеек) за 1 обыкновенную акцию", "1.12"),
    ],
)
def test_prices_that_were_wrong_in_the_azipi_parser(text: str, expected: str) -> None:
    assert parse_price(text) == expected


def test_price_absent_returns_none() -> None:
    assert parse_price("порядок определения цены указан в приложении") is None
