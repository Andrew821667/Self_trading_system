"""Ловушки разбора сообщений e-disclosure.ru.

Каждый случай здесь — не гипотеза, а строка из конкретного сохранённого
сообщения, на которой парсер молча выдавал неверное число. Молча — ключевое
слово: ошибка не роняла разбор, она подставляла правдоподобную цену или дату,
и заметить её можно было только сверкой с текстом. Поэтому тесты держат
именно эти формулировки, а не упрощённые образцы.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))

from parse_interfax_events import clauses, parse_date, parse_price


@pytest.mark.parametrize(
    ("text", "expected"),
    [
        # Рубли целые + копейки отдельно — их надо сложить.
        ("481 (Четыреста восемьдесят один) рубль 68 копеек", "481.68"),
        # То же, но копейки продублированы прописью.
        ("234 (двести тридцать четыре) рубля 75 (семьдесят пять) копеек", "234.75"),
        # Рубли уже дробные, а скобка повторяет ту же цену другими словами.
        # Сложение давало 1,50 — ровно вдвое больше действительной цены выкупа.
        ("0,75 рубля (75 копеек) за 1 (одну) акцию", "0.75"),
        ("80,81 рублей (Восемьдесят рублей 81 копейка) за одну акцию", "80.81"),
        # Цена ниже рубля: слова "рубль" рядом с числом нет вовсе.
        ("61 (шестьдесят одна) копейка за 1 (одну) акцию", "0.61"),
        # Слово "рубль" есть только внутри расшифровки прописью.
        ("1,89 (один рубль восемьдесят девять копеек) за одну акцию", "1.89"),
        # Доли копейки — законная цена, а не сбой распознавания.
        ("Цена приобретения одной обыкновенной акции составляет 0,00289 рублей", "0.00289"),
        # Вытеснение по ст. 84.8 после санации: цена записана дробью.
        (
            "1 / 4 507 984 112 (Одна четырехмиллиардная ... доля) рубля за 1 (одну) акцию",
            "0.0000000002",
        ),
    ],
)
def test_parse_price(text: str, expected: str) -> None:
    assert parse_price(text) == expected


@pytest.mark.parametrize(
    ("text", "expected"),
    [
        ("о котором составлено сообщение: 30.07.2025", "2025-07-30"),
        # Прописью — в шапке и в пункте 2.4 одного и того же документа.
        ("Дата получения эмитентом требования: 14 декабря 2020 года", "2020-12-14"),
        ("о котором составлено сообщение 02 июня 2020 г.", "2020-06-02"),
        ("31 марта 2025 года", "2025-03-31"),
        ("1 мая 2021 г.", "2021-05-01"),
    ],
)
def test_parse_date(text: str, expected: str) -> None:
    assert parse_date(text) == expected


def test_clauses_split_without_trailing_dot() -> None:
    """Точка после номера пункта ставится не всегда — в одном документе по-разному.

    Раньше требование точки склеивало весь раздел 2 в один пункт, и «дата
    наступления события» отвечала первым, что нашлось после ближайшего
    двоеточия: у Русполимета это была дата госрегистрации выпуска 15.12.2005.
    """
    text = (
        "1.8. Дата наступления события 27.07.2020 "
        "2. Содержание сообщения "
        "2.1 Лицо, направившее предложение: ООО «Мотор-инвест». "
        "2.6 Предлагаемая цена: 61 копейка за 1 акцию."
    )
    assert [num for num, _body in clauses(text)] == ["1.8", "2.1", "2.6"]


def test_clauses_ignore_numbers_that_are_not_clause_marks() -> None:
    """Дата в конце предложения и ссылка на устав — не номера пунктов.

    «27.07.2020. 2.4» содержит «07.2020. », а «п. п. 12.4.2 и 20.1 устава» —
    «20.1 »; обе подстроки внешне неотличимы от номера пункта.
    """
    text = (
        "2.3 Дата получения: 27.07.2020. "
        "2.4 Признаки бумаг: акции обыкновенные. "
        "2.9. В соответствии с п. п. 12.4.2 и 20.1 устава сообщение публикуется."
    )
    assert [num for num, _body in clauses(text)] == ["2.3", "2.4", "2.9"]
